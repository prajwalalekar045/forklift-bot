#!/usr/bin/env python3
"""Generate painted floor markings for the AWS small warehouse and inject them into small_warehouse.sdf.

Usage: python3 tools/gen_floor_markings.py            # rewrite the block in the world file
       python3 tools/gen_floor_markings.py --print    # only print the SDF

What it draws (visual only, no collision, 4 mm thick, so the lidar plane at 0.34 m and the physics
never see it):
  * a yellow bay zone around each pick/drop bay with a stop bar at the aisle edge
  * a dashed yellow AGV lane from the start area to each bay

Keep BAYS in sync with docking.yaml / small_warehouse.sdf. The AWS floor top is at z = 0.034 m
(GroundB mesh height 0.124 m, placed at z = -0.090 m), so marks sit at 0.0365 m.
"""
import argparse
import os

Z = 0.0365
T = 0.004
YELLOW = (0.95, 0.75, 0.00)
WHITE = (0.90, 0.90, 0.90)

# name, centre x, wall-side y (pallet centre), direction the robot drives (+1 = +y, -1 = -y)
BAYS = [("a", -3.75, 9.8, +1), ("b", 1.8, -9.8, -1)]
ZONE_W = 1.4          # across the bay
ZONE_L = 1.95         # from the wall-side edge towards the aisle
EDGE = 0.07           # border line width
LANE_W = 0.08
DASH, GAP = 0.40, 0.30

BEGIN = "<!-- BEGIN floor_markings (generated by tools/gen_floor_markings.py) -->"
END = "<!-- END floor_markings -->"


class Marks:
    def __init__(self):
        self.items = []

    def box(self, cx, cy, sx, sy, colour):
        self.items.append((cx, cy, sx, sy, colour))

    def sdf(self):
        out = [BEGIN,
               '    <model name="floor_markings">',
               '      <static>true</static>',
               '      <link name="link">']
        for i, (cx, cy, sx, sy, c) in enumerate(self.items):
            out.append(
                f'        <visual name="mark_{i:03d}"><cast_shadows>false</cast_shadows>'
                f'<pose>{cx:.4f} {cy:.4f} {Z} 0 0 0</pose>'
                f'<geometry><box><size>{sx:.4f} {sy:.4f} {T}</size></box></geometry>'
                f'<material><ambient>{c[0]} {c[1]} {c[2]} 1</ambient><diffuse>{c[0]} {c[1]} {c[2]} 1</diffuse>'
                f'<specular>0 0 0 1</specular></material></visual>')
        out += ['      </link>', '    </model>', '    ' + END]
        return "\n".join(out)


def build():
    m = Marks()
    for _, cx, cy, d in BAYS:
        wall_y = cy + d * 0.35               # just in front of the rack panel
        aisle_y = wall_y - d * ZONE_L        # aisle edge of the zone
        mid_y = (wall_y + aisle_y) / 2
        # side lines, wall-side line, stop bar (twice as wide) at the aisle edge
        m.box(cx - ZONE_W / 2, mid_y, EDGE, ZONE_L, YELLOW)
        m.box(cx + ZONE_W / 2, mid_y, EDGE, ZONE_L, YELLOW)
        m.box(cx, wall_y, ZONE_W + EDGE, EDGE, YELLOW)
        m.box(cx, aisle_y, ZONE_W + EDGE, 2 * EDGE, YELLOW)
        # dashed AGV lane from the start area to the zone
        y_start = 0.7 if d > 0 else -1.0
        y_end = aisle_y - d * 0.5
        y = y_start
        while (y_end - y) * d > DASH:
            m.box(cx, y + d * DASH / 2, LANE_W, DASH, YELLOW)
            y += d * (DASH + GAP)
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true")
    args = ap.parse_args()
    block = build().sdf()
    if args.print:
        print(block)
        return
    path = os.path.join(os.path.dirname(__file__), "..", "src", "forklift_gazebo", "worlds", "small_warehouse.sdf")
    text = open(path).read()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head.rstrip(" ") + "    " + block + tail
    else:
        marker = "<!-- ===== end bays ===== -->"
        assert marker in text, "bay block marker not found"
        text = text.replace(marker, marker + "\n\n    " + block + "\n")
    open(path, "w").write(text)
    print(f"floor markings written to {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
